//go:build ignore

// Command build_site regenerates the static site from pre-generated reports.
//
// The site is what a reviewer opens with no server and no network: three real
// incident reports, the benchmark table, and an index that links them. Nothing is
// fetched at view time, so it works from a cloned folder or from GitHub Pages.
//
// Usage:
//
//	go run scripts/build_site.go
package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// reportSeeds are the seeds whose demos become the gallery. Fixed on purpose: the
// site must not change because someone re-ran a command.
// fixtureGallery is the hand-checked captures, in the order they are shown.
var fixtureGallery = []struct{ Name, Title string }{
	{"pool-exhaustion", "Connection-pool exhaustion — db-proxy breaks, api and web follow"},
	{"steady-state", "Healthy capture — the tool must say insufficient evidence"},
	{"messy-input", "Dirty capture — four bad lines, each rejected for a different reason"},
}

var reportSeeds = []struct {
	Seed  int
	Title string
}{
	{Seed: 3, Title: "Connection-pool exhaustion in a database proxy"},
	{Seed: 7, Title: "Partial network partition between two services"},
	{Seed: 12, Title: "Bad deploy: errors immediately after a release"},
}

func main() {
	siteDir := "site"
	if err := os.MkdirAll(siteDir, 0o755); err != nil {
		fail(err)
	}

	// Each report is generated fresh by the demo command, into its own folder.
	for _, r := range reportSeeds {
		dir := filepath.Join(siteDir, fmt.Sprintf("report-%d", r.Seed))
		if err := os.MkdirAll(dir, 0o755); err != nil {
			fail(err)
		}
		run("go", "run", "./cmd/itm", "demo",
			"--seed", fmt.Sprint(r.Seed), "--out", dir)
	}

	// The hand-checked fixtures, so a visitor can see a report generated from a
	// capture they can read in a minute.
	for _, fx := range fixtureGallery {
		dir := filepath.Join(siteDir, "fixture-"+fx.Name)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			fail(err)
		}
		run("go", "run", "./cmd/itm", "analyze",
			"--logs", filepath.Join("fixtures", fx.Name, "logs.jsonl"),
			"--spans", filepath.Join("fixtures", fx.Name, "spans.jsonl"),
			"--out", dir)
	}

	// Benchmark table, if it exists.
	benchMD := ""
	if blob, err := os.ReadFile("BENCHMARK.md"); err == nil {
		benchMD = string(blob)
	}

	index := buildIndex(benchMD)
	if err := os.WriteFile(filepath.Join(siteDir, "index.html"), []byte(index), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %s/index.html (%d bytes)\n", siteDir, len(index))
}

// buildIndex renders the gallery page. It is one self-contained file: inline CSS,
// no scripts, no external requests.
func buildIndex(benchMD string) string {
	var b strings.Builder
	b.WriteString("<!DOCTYPE html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">")
	b.WriteString("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">")
	b.WriteString("<title>Incident Time Machine — example reports</title>")
	b.WriteString("<style>")
	b.WriteString(siteCSS)
	b.WriteString("</style></head><body><main>\n")

	b.WriteString("<h1>Incident Time Machine</h1>\n")
	b.WriteString("<p class=\"lede\">Feed ITM the logs and traces from an outage and it reconstructs what ")
	b.WriteString("happened: a timeline, a dependency graph, and a ranked list of probable root causes ")
	b.WriteString("with evidence.</p>\n")
	b.WriteString("<p class=\"note\">Every report below is generated by <code>itm demo</code> from a seeded ")
	b.WriteString("simulated incident, so the true cause is known and the ranking can be checked against it. ")
	b.WriteString("This page and the reports it links are fully static: no server, no network.</p>\n")

	b.WriteString("<h2>Hand-checked fixtures</h2>\n")
	b.WriteString("<p class=\"note\">Small captures committed in <code>fixtures/</code> that you can read in a minute. ")
	b.WriteString("Each one proves a different behaviour, and the expected result is documented next to it.</p>\n")
	b.WriteString("<ul class=\"gallery\">\n")
	for _, fx := range fixtureGallery {
		fmt.Fprintf(&b, "<li><a href=\"fixture-%s/report.html\">%s</a>", fx.Name, htmlEscape(fx.Title))
		fmt.Fprintf(&b, "<span class=\"meta\"><a href=\"fixture-%s/summary.md\">markdown</a> · ", fx.Name)
		fmt.Fprintf(&b, "<a href=\"fixture-%s/result.json\">json</a></span></li>\n", fx.Name)
	}
	b.WriteString("</ul>\n")

	b.WriteString("<h2>Simulated reports</h2>\n<ul class=\"gallery\">\n")
	sorted := append([]struct {
		Seed  int
		Title string
	}(nil), reportSeeds...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Seed < sorted[j].Seed })
	for _, r := range sorted {
		fmt.Fprintf(&b, "<li><a href=\"report-%d/report.html\">%s</a>", r.Seed, htmlEscape(r.Title))
		fmt.Fprintf(&b, "<span class=\"meta\">scenario seed %d · ", r.Seed)
		fmt.Fprintf(&b, "<a href=\"report-%d/summary.md\">markdown</a> · ", r.Seed)
		fmt.Fprintf(&b, "<a href=\"report-%d/result.json\">json</a></span></li>\n", r.Seed)
	}
	b.WriteString("</ul>\n")

	if benchMD != "" {
		b.WriteString("<h2>Benchmark</h2>\n<pre class=\"bench\">")
		b.WriteString(htmlEscape(benchMD))
		b.WriteString("</pre>\n")
	}

	b.WriteString("<footer>Generated by <code>go run scripts/build_site.go</code>. MIT licensed.</footer>\n")
	b.WriteString("</main></body></html>\n")
	return b.String()
}

